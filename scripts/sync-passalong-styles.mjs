// Copies Passalong's fonts and design tokens into this repo, so the Mac app and the site share its styles.
// Only the fonts, the :root tokens and the theme switch are taken; Passalong's page rules are not.
// Usage: node scripts/sync-passalong-styles.mjs [path to passalong repo]
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2] ?? join(here, '..', 'passalong');
const css = readFileSync(join(src, 'apps/web/app/assets/css/styles.css'), 'utf8');
const cut = (from, to) => { const a = css.indexOf(from), b = css.indexOf(to, a); if (a < 0 || b < 0) throw new Error(`marker not found: ${from} … ${to}`); return css.slice(a, b); };
const fonts = cut('/* ---- fonts', '/* ---- border reset');
const tokens = cut('/* ---- tokens', '*,\n*::before,\n*::after {\n  box-sizing');
const rev = execFileSync('git', ['-C', src, 'log', '-1', '--format=%h', '--', 'apps/web/app/assets/css/styles.css'], { encoding: 'utf8' }).trim();

writeFileSync(join(here, 'styles/passalong.css'),
  `/* Generated by scripts/sync-passalong-styles.mjs from passalong apps/web/app/assets/css/styles.css @ ${rev}.\n   Do not edit here; change Passalong and re-run the script. */\n\n${fonts}${tokens}`);
const FONTS = ['onest-var.woff2', 'newsreader-var.woff2', 'newsreader-italic-var.woff2', 'jetbrains-mono-var.woff2'];
for (const dir of ['public/fonts', 'site/public/fonts']) {
  mkdirSync(join(here, dir), { recursive: true });
  for (const f of FONTS) copyFileSync(join(src, 'apps/web/public/fonts', f), join(here, dir, f));
}
console.log(`styles/passalong.css from ${rev}; ${FONTS.length} fonts into public/fonts and site/public/fonts`);
